print("=============Positional parameter===============")

def details(name,age):
    print("Student Name=",name)
    print("Student Age=", age)

details("Akshay",21)
print("===========")
details(21,"Akshay")

print("=============Positional parameter===============")

def calculation(i,j):
    print("number i =",i)
    print("number j =",j)
print("=================")
calculation(10,20)
calculation(20,10)

print("=============Positional parameter===============")

def company(name,empid):
    print("Emp Name = ",name)
    print("Emp Name = ",empid)

company("Akshay",21)
print("==============")
company(21,"Akshay")
print("=================================================")




