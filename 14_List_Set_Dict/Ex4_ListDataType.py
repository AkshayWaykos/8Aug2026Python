s1=[123,"Akshay",12,'sagar',12,10,20,30]

#append - at end add data.
s1.append("Shiva")
print(s1)

#extends - Add list in existing list
s1.extend([10,20,30,40])
print(s1)

#insert  - insert data on 1 index
s1.insert(1,"Trupti")
print(s1)

#pop   - last one remove from list
s1.pop()
print(s1)

#pop(index) - remove 3 no data type from list
s1.pop(3)
print(s1)

#remove - remove particulate data from list
s1.remove("sagar")
print(s1)


