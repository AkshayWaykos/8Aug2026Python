print("=====All Loops =======")

for i in range(1,5):
    print(i)
print("--------------------")
for i in range(5,1,-1):
    print(i)
print("--------------------")
for i in range(1,5):
    print("#"*i)
for i in range(5,0,-1):
    print("#"*i)
print("--------------------")

for i in range(2,11,2):
    print("Even no=",i)
print("--------------------")

for i in range(1,11,2):
    print("Odd no=",i)
print("---------------------")
for i in range(10,0,-2):
    print(i)
print("---------------------")